CREATE TABLE app_user (
  id BIGSERIAL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE wishlist (
  id BIGSERIAL PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  title VARCHAR(100) NOT NULL,
  description VARCHAR(500),
  share_token VARCHAR(64) NOT NULL UNIQUE,
  visibility VARCHAR(16) NOT NULL DEFAULT 'PRIVATE' CHECK (visibility IN ('PRIVATE','LINK','PUBLIC')),
  gift_list BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_wishlist_owner ON wishlist(owner_id);
CREATE TABLE wishlist_item (
  id BIGSERIAL PRIMARY KEY,
  wishlist_id BIGINT NOT NULL REFERENCES wishlist(id) ON DELETE CASCADE,
  title VARCHAR(180) NOT NULL,
  product_url VARCHAR(2048) NOT NULL,
  image_url VARCHAR(2048),
  price NUMERIC(12,2),
  currency VARCHAR(3) NOT NULL DEFAULT 'GBP',
  note VARCHAR(1000),
  reserved BOOLEAN NOT NULL DEFAULT FALSE,
  reserved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_wishlist_item_parent ON wishlist_item(wishlist_id);
